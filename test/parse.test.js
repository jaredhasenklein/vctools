import { readFileSync } from 'node:fs';
import Papa from 'papaparse';
import { describe, it, expect } from 'vitest';
import { fixMojibake, detectProgram, findHeaderRow, readReportText, resolveFields, toRecords } from '../lib/vms/parse.js';
import { fieldForHeader } from '../lib/vms/fields.js';

const fixture = readFileSync('test/fixtures/training-and-certifications.csv', 'utf8');
const read = (text) => readReportText(text, Papa);
const TC_NEEDS = {
  preferredFirstName: { required: true },
  lastName: { required: true },
  email: { required: true },
  role: { required: true },
  courseName: { required: true },
  completionDate: {},
};

describe('fields', () => {
  it('matches headers exactly after normalizing, never partially', () => {
    expect(fieldForHeader(' Consent and Release Status ')).toBe('consentReleaseStatus');
    expect(fieldForHeader('Emergency Contact Phone Number')).toBe('emergencyContactPhone');
    expect(fieldForHeader('Phone')).toBe('phone');
    expect(fieldForHeader('Favorite Color')).toBeNull();
  });
});

describe('preamble', () => {
  it('reads event details, coordinators, and program', () => {
    const { meta } = read(fixture);
    expect(meta.report).toBe('Training and Certifications');
    expect(meta.event).toBe('CA-Testville-Example Kickoff - FRC');
    expect(meta.program).toBe('FRC');
    expect(meta.coordinators).toEqual(['Pat Example']);
  });

  it('repairs mis-encoded characters', () => {
    expect(read(fixture).meta.season).toBe('2027 - BIOCORE™ presented by Haas');
    expect(fixMojibake('Already fine ™')).toBe('Already fine ™');
    expect(fixMojibake('Plain text')).toBe('Plain text');
  });

  it('detects program from names without a suffix', () => {
    expect(detectProgram('FIRST Tech Challenge Qualifier')).toBe('FTC');
    expect(detectProgram('Something - fll')).toBe('FLL');
    expect(detectProgram('Mystery Event')).toBeNull();
  });
});

describe('header row', () => {
  it('is found on row 19 of a standard export', () => {
    const rows = Papa.parse(fixture).data;
    expect(findHeaderRow(rows)).toBe(18);
  });

  it('is found when FIRST adds or removes preamble rows', () => {
    const longer = fixture.replace('Date: 10/20/2026', 'Date: 10/20/2026\nGenerated By: Someone\nFilter: All');
    expect(read(longer).rows).toHaveLength(2);
    const shorter = fixture.replace(/WARNING[\s\S]*?privacy@firstinspires\.org\."\n/, '');
    expect(read(shorter).rows).toHaveLength(2);
  });

  it('throws a readable error for a non-VMS file', () => {
    expect(() => read('a,b,c\n1,2,3')).toThrow(/does not look like a VMS report/);
  });
});

describe('columns', () => {
  it('resolves by name, not position, and keeps quoted commas in one cell', () => {
    const reordered = fixture.replace(
      'Minor,Preferred First Name,Last Name,Email',
      'Email,Minor,Preferred First Name,Last Name',
    ).replace('No,Alex,Tester,alex@example.com', 'alex@example.com,No,Alex,Tester')
      .replace('No,Jordan,Fixture,jordan@example.com', 'jordan@example.com,No,Jordan,Fixture');
    const report = read(reordered);
    const { columns, missing } = resolveFields(report, TC_NEEDS);
    expect(missing).toEqual([]);
    const [alex] = toRecords(report, columns);
    expect(alex).toMatchObject({ preferredFirstName: 'Alex', email: 'alex@example.com', role: 'Judge, Judge Advisor' });
  });

  it('accepts a renamed column through its alias and reports new columns', () => {
    const report = read(fixture.replace(',Course Name,', ',Course,').replace(',Required?', ',Required?,Badge Color'));
    expect(resolveFields(report, TC_NEEDS).missing).toEqual([]);
    expect(report.unknownHeaders).toEqual(['Badge Color']);
  });

  it('lists a removed column as missing until the user maps or skips it', () => {
    const report = read(fixture.replace(',Course Name,', ',Training Module,'));
    expect(resolveFields(report, TC_NEEDS).missing).toEqual(['courseName']);

    const mapped = resolveFields(report, TC_NEEDS, { courseName: 'Training Module' });
    expect(mapped.missing).toEqual([]);
    expect(toRecords(report, mapped.columns)[0].courseName).toBe('FRC Judge Training');

    const skipped = resolveFields(report, TC_NEEDS, { courseName: null });
    expect(skipped.missing).toEqual([]);
    expect(skipped.columns.courseName).toBeNull();
    expect(toRecords(report, skipped.columns)[0].courseName).toBe('');
  });

  it('asks again when a saved mapping points at a column that is gone', () => {
    const report = read(fixture.replace(',Course Name,', ',Training Module,'));
    expect(resolveFields(report, TC_NEEDS, { courseName: 'Old Name' }).missing).toEqual(['courseName']);
  });

  it('rejects field keys that are not in the registry', () => {
    expect(() => resolveFields(read(fixture), { nope: {} })).toThrow(/Unknown field/);
  });
});
